"""评测报告生成器。

输入: annotated cases + metrics dict
输出: Markdown 格式报告
"""
from __future__ import annotations

from datetime import datetime
from typing import Any


def generate_report(
    cases: list[dict[str, Any]],
    metrics: dict[str, Any],
    dataset_name: str = "customer_service",
) -> str:
    lines: list[str] = []
    lines.append(f"# tao-ai 评测报告 — {dataset_name}")
    lines.append(f"")
    lines.append(f"**时间**: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S')} UTC")
    lines.append(f"**用例数**: {metrics.get('total_cases', len(cases))}")
    lines.append("")

    lines.append("## 汇总指标")
    lines.append("")
    lines.append("| 指标 | 值 |")
    lines.append("| --- | --- |")
    for k, v in metrics.items():
        if k == "total_cases":
            continue
        pct = f"{v * 100:.1f}%" if isinstance(v, float) else str(v)
        label = k.replace("_", " ").title()
        lines.append(f"| {label} | {pct} |")
    lines.append("")

    lines.append("## 用例明细")
    lines.append("")
    lines.append("| ID | Query | Exp Skill | Act Skill | Match | Tools | RAG | Approval |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")

    for c in cases:
        cid = c.get("id", "?")
        query = c.get("query", "")[:30]
        exp_skill = c.get("expected_skill", "")
        act_skill = c.get("actual_skill", "")
        match = "Y" if exp_skill == act_skill else "**N**"

        exp_tools = set(c.get("expected_tools", []))
        act_tools = set(c.get("actual_tools", []))
        tool_ok = "Y" if exp_tools <= act_tools else "N"

        exp_rag = set(c.get("expected_rag_docs", []))
        act_rag = set(c.get("actual_rag_docs", []))
        rag_ok = "Y" if not exp_rag or (exp_rag & act_rag) else "N"

        appr = "Y" if c.get("approval_triggered") else "-"

        lines.append(f"| {cid} | {query} | {exp_skill} | {act_skill} | {match} | {tool_ok} | {rag_ok} | {appr} |")

    lines.append("")
    lines.append("---")
    lines.append("*Generated by tao-ai eval framework*")

    return "\n".join(lines)
